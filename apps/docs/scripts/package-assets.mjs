// Endpoint pages moved from /docs/api/<tag>/* to /docs/api/reference/<tag>/*
// when the hand-written API guides took over /docs/api. Read the tags from the
// build so a new tag is redirected without editing this file.
const listDirs = async (path) =>
  (await readdir(path, { withFileTypes: true })).filter((entry) => entry.isDirectory()).map((entry) => entry.name);

const apiGuides = new Set(await listDirs(resolve(dist, 'api')));
const apiTags = await listDirs(resolve(dist, 'api/reference'));
const clashing = apiTags.filter((tag) => apiGuides.has(tag));
if (clashing.length > 0) {
  throw new Error(`[docs] API tags clash with guide pages under /docs/api: ${clashing.join(', ')}`);
}

const API_TAG_REDIRECTS = apiTags.map((tag) => `/docs/api/${tag}/* /docs/api/reference/${tag}/:splat 301`).join('\n');

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

await cp(dist, resolve(out, 'docs'), { recursive: true });
await writeFile(resolve(out, '_redirects'), `${REDIRECTS}\n${API_TAG_REDIRECTS}\n`);

console.log('[docs] Packaged dist/ -> build/docs/ with _redirects');
