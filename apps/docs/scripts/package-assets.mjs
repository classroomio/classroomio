/**
 * Packages `blume build` output for the assets-only Cloudflare Worker.
 *
 * Two things have to be reconciled:
 *
 * 1. `deployment.base: '/docs'` makes Blume emit URLs like `/docs/foo`, but it
 *    does NOT nest the output — pages land in `dist/foo/index.html`. The worker
 *    is asked for `/docs/foo` (the website proxies the full path through), so
 *    the build is moved under `build/docs/` to line up with the served paths.
 *
 * 2. Blume's own `redirects` (blume.config.ts) only match exact paths — no
 *    wildcards — and most of ours are `/old/*` splat rules, so most still live
 *    here as a Cloudflare `_redirects` file, which must sit at the root of the
 *    assets directory. (The one exact-path root→/developers redirect is
 *    declared natively too, since this file has no effect on `blume dev`.)
 */
import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = resolve(root, 'dist');
const out = resolve(root, 'build');

// Guides used to live under content/docs/guides and redirect from their old
// root-level slugs; they moved to the standalone apps/help app (served at
// /help, no redirects from the old /docs/guides/* URLs — clean break by
// design). Only non-guide redirects remain here.
//
// The Platform tab is gone. Its concept/overview pages (audience, cohorts,
// community, course, enterprise-sso, organization, student-dashboard, tags)
// moved verbatim into apps/help's Reference section alongside the Glossary
// (terminology's replacement) — same content, new home, since Help already
// serves the same broad audience these pages were written for. Quickstart
// moved into Help's Get started group. what-is-classroomio had no unique
// content beyond linking elsewhere, so it was dropped rather than moved.
const REDIRECTS = `# Generated by scripts/package-assets.mjs — do not edit.
/docs /docs/developers 301
/docs/ /docs/developers 301
/docs/home /docs/developers 301
/docs/how-to-guides/* /docs/:splat 301
/docs/api/reference /docs/api 301

/docs/contributor-guides /docs/contributing 301
/docs/contributor-guides/* /docs/contributing/:splat 301
/docs/guides/contributing /docs/contributing 301
/docs/guides/contributing/* /docs/contributing/:splat 301
/docs/developers/contributing /docs/contributing 301
/docs/developers/contributing/* /docs/contributing/:splat 301

/docs/mcp /docs/developers/mcp 301
/docs/guides/mcp /docs/developers/mcp 301
/docs/token-auth /docs/developers/token-auth 301
/docs/guides/token-auth /docs/developers/token-auth 301

/docs/self-hosted/configuration/sso /docs/self-hosted/enterprise 301

/docs/audience /help/reference/audience 301
/docs/cohorts /help/reference/cohorts 301
/docs/community /help/reference/community 301
/docs/course /help/reference/course 301
/docs/enterprise-sso /help/reference/enterprise-sso 301
/docs/organization /help/reference/organization 301
/docs/quickstart/signup /help/get-started/signup 301
/docs/quickstart/onboarding /help/get-started/onboarding 301
/docs/student-dashboard /help/reference/student-dashboard 301
/docs/tags /help/reference/tags 301
/docs/terminology /help/reference/glossary 301
/docs/what-is-classroomio /docs/developers 301
`;

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

await cp(dist, resolve(out, 'docs'), { recursive: true });
await writeFile(resolve(out, '_redirects'), REDIRECTS);

console.log('[docs] Packaged dist/ -> build/docs/ with _redirects');
