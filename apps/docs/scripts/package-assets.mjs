/**
 * Packages `blume build` output for the assets-only Cloudflare Worker.
 *
 * Two things have to be reconciled:
 *
 * 1. `deployment.base: '/docs'` makes Blume emit URLs like `/docs/foo`, but it
 *    does NOT nest the output — pages land in `dist/foo/index.html`. The worker
 *    is asked for `/docs/foo` (the website proxies the full path through), so
 *    the build is moved under `build/docs/` to line up with the served paths.
 *
 * 2. Astro's own `redirects` are unusable under a base: it prefixes a
 *    redirect's source but not its target, emitting `url=/developers/mcp`
 *    rather than `/docs/developers/mcp`. So the redirects are written here as
 *    a Cloudflare `_redirects` file, which must sit at the root of the assets
 *    directory.
 */
import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = resolve(root, 'dist');
const out = resolve(root, 'build');

// Guides used to live under content/docs/guides and redirect from their old
// root-level slugs; they moved to the standalone apps/help app (served at
// /help, no redirects from the old /docs/guides/* URLs — clean break by
// design). Only non-guide redirects remain here.
const REDIRECTS = `# Generated by scripts/package-assets.mjs — do not edit.
/docs/ /docs 301
/docs/home /docs 301
/docs/how-to-guides/* /docs/:splat 301
/docs/api/reference /docs/api 301

/docs/contributor-guides /docs/developers/contributing 301
/docs/contributor-guides/* /docs/developers/contributing/:splat 301
/docs/guides/contributing /docs/developers/contributing 301
/docs/guides/contributing/* /docs/developers/contributing/:splat 301

/docs/mcp /docs/developers/mcp 301
/docs/guides/mcp /docs/developers/mcp 301
/docs/token-auth /docs/developers/token-auth 301
/docs/guides/token-auth /docs/developers/token-auth 301

/docs/self-hosted/configuration/sso /docs/self-hosted/enterprise 301
`;

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

await cp(dist, resolve(out, 'docs'), { recursive: true });
await writeFile(resolve(out, '_redirects'), REDIRECTS);

console.log('[docs] Packaged dist/ -> build/docs/ with _redirects');
