/*
 * Generates site/copy.js: the dashboard's en.json (the product copy) plus the exercise question labels,
 * with a tiny t(key, vars) that handles {var} and ICU plural, so the public academy pages and the learner
 * app use the product's strings verbatim. Run: node tools/site-bundle/extract-copy.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../../..');
const en = JSON.parse(fs.readFileSync(path.join(repo, 'apps/dashboard/src/lib/utils/translations/en.json'), 'utf8'));

const labelsSource = fs.readFileSync(
  path.join(repo, 'apps/dashboard/src/lib/features/course/components/exercise/question-labels.ts'),
  'utf8'
);
const lookup = (key) => key.split('.').reduce((node, part) => (node == null ? node : node[part]), en);
const questionLabels = {};

for (const match of labelsSource.matchAll(/'([a-z_.]+)':\s*t\.get\(\s*'([^']+)'\s*\)/g)) {
  const value = lookup(match[2]);

  if (typeof value === 'string') questionLabels[match[1]] = value;
}

const runtime = `
  const EN = ${JSON.stringify(en)};
  const QUESTION_LABELS = ${JSON.stringify(questionLabels)};

  function lookup(key) {
    return key.split('.').reduce((node, part) => (node == null ? node : node[part]), EN);
  }

  function plural(text, vars) {
    return text.replace(/\\{(\\w+), plural, ((?:[^{}]|\\{[^{}]*\\})*)\\}/g, (all, name, body) => {
      const count = Number(vars?.[name] ?? 0);
      const forms = {};

      body.replace(/(\\w+|=\\d+) \\{([^{}]*)\\}/g, (m, form, text) => {
        forms[form] = text;
      });

      const form = forms['=' + count] ?? (count === 1 ? forms.one : forms.other) ?? forms.other ?? '';

      return form.replace(/#/g, String(count));
    });
  }

  function t(key, vars) {
    const value = lookup(key);

    if (typeof value !== 'string') return key;

    return plural(value, vars).replace(/\\{(\\w+)\\}/g, (all, name) => (vars && name in vars ? String(vars[name]) : all));
  }

  window.cioCopy = { t, EN, questionLabels: QUESTION_LABELS };
`;

fs.writeFileSync(
  path.join(here, '../../site/copy.js'),
  `/* Generated by tools/site-bundle/extract-copy.mjs from apps/dashboard en.json. Do not edit. */\n(function () {${runtime}})();\n`
);
