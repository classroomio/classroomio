"""Lifts the Machine illustrations out of packages/ui into machines.js.

The Svelte components are static SVG markup with SMIL animation, so the body is copied
verbatim. Re-run this after the source components change:

    python3 tools/extract-machines.py
"""
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[3]
src = root / 'packages/ui/src/custom/animation/machines'
out = pathlib.Path(__file__).resolve().parents[1] / 'machines.js'

MACHINES = {'trainingLine': 'training-line.svelte', 'brandStand': 'brand-stand.svelte'}

frame = (src / 'machine-frame.svelte').read_text()
css = re.search(r'<style>(.*?)</style>', frame, re.S).group(1)
css = re.sub(r':global\((.*?)\)', r'\1', css)

entries = {}
for key, name in MACHINES.items():
    text = (src / name).read_text()
    match = re.search(r'<MachineFrame viewBox="([^"]+)"[^>]*>(.*?)</MachineFrame>', text, re.S)
    entries[key] = {'viewBox': match.group(1), 'body': match.group(2).strip()}

out.write_text(
    '/* Generated by tools/extract-machines.py from packages/ui/src/custom/animation/machines. */\n'
    f'window.MACHINE_CSS = {json.dumps(css)};\n'
    f'window.MACHINE_SOURCE = {json.dumps(entries)};\n'
)
print('wrote', out, {k: len(v['body']) for k, v in entries.items()})
