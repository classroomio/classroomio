CREATE FUNCTION pg_temp.normalize_lesson_tabs(order_json jsonb) RETURNS integer[] LANGUAGE plpgsql IMMUTABLE AS $fn$
DECLARE
  tabs integer[] := ARRAY[]::integer[];
  tab_id integer;
BEGIN
  IF order_json IS NOT NULL AND jsonb_typeof(order_json) = 'array' THEN
    SELECT COALESCE(array_agg((entry->>'id')::integer ORDER BY ordinality), ARRAY[]::integer[])
    INTO tabs
    FROM jsonb_array_elements(order_json) WITH ORDINALITY AS entries(entry, ordinality)
    WHERE entry->>'id' IN ('1', '2', '3', '4');
  END IF;

  IF cardinality(tabs) = 0 OR tabs = ARRAY[1, 2, 3, 4] THEN
    RETURN ARRAY[3, 1, 2, 4];
  END IF;

  FOREACH tab_id IN ARRAY ARRAY[3, 1, 2, 4] LOOP
    IF NOT tab_id = ANY(tabs) THEN
      tabs := tabs || tab_id;
    END IF;
  END LOOP;

  RETURN tabs;
END
$fn$;--> statement-breakpoint

